#!/usr/bin/env python3
"""CLI: evaluate labelled documents against ground truth."""

from __future__ import annotations

import argparse
import json
import logging
from dataclasses import replace
from pathlib import Path

from src.config import get_settings
from src.evaluation.evaluator import Evaluator, format_report_table
from src.pipeline import InvoicePipeline


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Evaluate invoice extraction on labelled documents.")
    parser.add_argument(
        "--mode",
        choices=["hybrid", "vision"],
        default=None,
        help="hybrid=text+OCR(+vision fallback); vision=skip OCR, scans/images go to vision LLM",
    )
    parser.add_argument(
        "--documents",
        type=Path,
        default=None,
        help="Labelled documents directory (default: data/raw/labelled)",
    )
    parser.add_argument(
        "--ground-truth",
        type=Path,
        default=None,
        help="Ground-truth JSON directory (default: data/ground_truth)",
    )
    parser.add_argument(
        "--report",
        type=Path,
        default=None,
        help="Optional path for machine-readable JSON report",
    )
    args = parser.parse_args(argv)

    settings = get_settings()
    mode = args.mode or settings.extraction_mode
    if mode in {"vision_only", "no_ocr"}:
        mode = "vision"
    settings = replace(settings, extraction_mode=mode)

    logging.basicConfig(level=settings.log_level)

    documents = args.documents or settings.data_raw_labelled
    ground_truth = args.ground_truth or settings.data_ground_truth

    if args.report is not None:
        report_path = args.report
        md_path = report_path.with_suffix(".md")
    elif mode == "vision":
        out_dir = settings.reports_dir / "vision_no_ocr"
        out_dir.mkdir(parents=True, exist_ok=True)
        report_path = out_dir / "evaluation_results.json"
        md_path = out_dir / "evaluation_report.md"
    else:
        # Current hybrid+escalate results (keep reports/ocr_baseline/ as historical 70% snapshot docs)
        out_dir = settings.reports_dir / "hybrid_escalate"
        out_dir.mkdir(parents=True, exist_ok=True)
        report_path = out_dir / "evaluation_results.json"
        md_path = out_dir / "evaluation_report.md"

    evaluator = Evaluator(InvoicePipeline(settings), mode=mode)
    report = evaluator.evaluate_labelled_dir(documents, ground_truth)
    table = format_report_table(report)
    print(table)

    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(json.dumps(report.to_dict(), indent=2), encoding="utf-8")

    md_path.write_text(
        f"# Evaluation Report ({mode})\n\n"
        f"Generated by `python evaluate.py --mode {mode}`.\n\n"
        "```text\n" + table + "\n```\n",
        encoding="utf-8",
    )

    # Keep top-level copies for convenience
    settings.reports_dir.mkdir(parents=True, exist_ok=True)
    (settings.reports_dir / "evaluation_results.json").write_text(
        json.dumps(report.to_dict(), indent=2), encoding="utf-8"
    )
    (settings.reports_dir / "evaluation_report.md").write_text(
        f"# Evaluation Report ({mode})\n\n```text\n{table}\n```\n",
        encoding="utf-8",
    )

    print(f"\nSaved JSON report: {report_path}")
    print(f"Saved markdown report: {md_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
